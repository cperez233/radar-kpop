"""Arma index.html: toma src/template.html y mete events.json como copia de respaldo.

Uso: python build.py
La pagina igual lee events.json por fetch cada 60 s; la copia embebida solo se usa si el fetch falla.
Tambien embebe:
- assets/photos/<id-del-grupo>.(webp|avif|jpg|jpeg|png) con su ancho y alto, para mostrarlas sin recortar.
- assets/chibis/roster.json (nombres de los miembros; lo genera tools/chibis.py).
- changelog.json, y con el mismo archivo reescribe CHANGELOG.md.
- siteUrl de config.js, si existe, para que la imagen de redes (og:image) sea una URL completa.
- Una política de seguridad (CSP) en <meta>, con el hash del script de datos.
Solo usa la biblioteca estandar de Python.
"""
import base64
import hashlib
import json
import re
import struct
from pathlib import Path

root = Path(__file__).parent
data = json.loads((root / "events.json").read_text(encoding="utf-8"))
tpl = (root / "src" / "template.html").read_text(encoding="utf-8")


def image_size(path: Path):
    """Ancho y alto de un PNG, JPEG o WebP leyendo solo la cabecera."""
    b = path.read_bytes()
    if b[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", b[16:24])
    if b[:4] == b"RIFF" and b[8:12] == b"WEBP":
        kind = b[12:16]
        if kind == b"VP8 ":
            w, h = struct.unpack("<HH", b[26:30])
            return w & 0x3FFF, h & 0x3FFF
        if kind == b"VP8L":
            bits = int.from_bytes(b[21:25], "little")
            return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
        if kind == b"VP8X":
            return int.from_bytes(b[24:27], "little") + 1, int.from_bytes(b[27:30], "little") + 1
    if b[:2] == b"\xff\xd8":
        i = 2
        while i < len(b) - 9:
            if b[i] != 0xFF:
                i += 1
                continue
            marker, size = b[i + 1], int.from_bytes(b[i + 2:i + 4], "big")
            if marker in (0xC0, 0xC1, 0xC2):
                h, w = struct.unpack(">HH", b[i + 5:i + 9])
                return w, h
            i += 2 + size
    return None


PHOTO_EXT = (".webp", ".avif", ".jpg", ".jpeg", ".png")
photos = {}
photo_dir = root / "assets" / "photos"
for g in data["groups"]:
    for ext in PHOTO_EXT:
        f = photo_dir / f"{g['id']}{ext}"
        if f.exists():
            size = image_size(f)
            photos[g["id"]] = {"file": f.name, "w": size[0], "h": size[1]} if size else {"file": f.name}
            break

roster_file = root / "assets" / "chibis" / "roster.json"
roster = json.loads(roster_file.read_text(encoding="utf-8")) if roster_file.exists() else {}

changes_file = root / "changelog.json"
changes = json.loads(changes_file.read_text(encoding="utf-8")) if changes_file.exists() else []
if changes:
    md = ["# Changelog", "", "Generated by `build.py` from `changelog.json`. The site shows the same list (in Spanish or English) under \"Novedades\".", ""]
    for v in changes:
        md += [f"## {v['version']} · {v['date']} · {v['title_en']}", ""]
        md += [f"- {x}" for x in v["en"]]
        md.append("")
    (root / "CHANGELOG.md").write_text("\n".join(md), encoding="utf-8")

config = (root / "config.js").read_text(encoding="utf-8")
m = re.search(r'siteUrl:\s*"([^"]*)"', config)
site = (m.group(1).strip() if m else "").rstrip("/")
og_image = f"{site}/assets/icons/og.png" if site else "assets/icons/og.png"
canonical = f'<link rel="canonical" href="{site}/">\n<meta property="og:url" content="{site}/">' if site else ""


def js(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


html = (tpl.replace("__DATA__", js(data)).replace("__PHOTOS__", js(photos))
        .replace("__ROSTER__", js(roster)).replace("__CHANGES__", js(changes))
        .replace("__OG_IMAGE__", og_image).replace("__CANONICAL__\n", canonical + ("\n" if canonical else "")))
# Política de seguridad (CSP) como <meta>, porque GitHub Pages no deja poner cabeceras.
# El único script en línea es el de los datos; se permite por su hash, que cambia en cada build.
inline = re.search(r"<script>(window\.RADAR_DATA0 = .*?)</script>", html, re.S).group(1)
digest = base64.b64encode(hashlib.sha256(inline.encode("utf-8")).digest()).decode()
csp = ("default-src 'self'; script-src 'self' 'sha256-" + digest + "'; "
       "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; "
       "img-src 'self' data: blob:; connect-src 'self' https:; manifest-src 'self'; worker-src 'self'; "
       "object-src 'none'; base-uri 'self'; form-action 'self'")
html = html.replace("__CSP__", f'<meta http-equiv="Content-Security-Policy" content="{csp}">')
(root / "index.html").write_text(html, encoding="utf-8")
print("index.html listo,", len(data["groups"]), "grupos,", len(photos), "fotos oficiales,",
      sum(len(v) for v in roster.values()), "chibis")
